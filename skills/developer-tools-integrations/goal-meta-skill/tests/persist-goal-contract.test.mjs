test('symlink or reparse target is refused without changing its destination', (t) => {
  const root = makeRepo();
  const outside = mkdtempSync(path.join(tmpdir(), 'goal-contract-outside-'));
  try {
    const destination = path.join(outside, 'outside.md');
    writeFileSync(destination, 'outside stays unchanged\n', 'utf8');
    try {
      symlinkSync(destination, path.join(root, 'GOAL.md'), 'file');
    } catch (error) {
      if (['EPERM', 'EACCES', 'UNKNOWN'].includes(error.code)) {
        t.skip(`symlink creation unavailable: ${error.code}`);
        return;
      }
      throw error;
    }
    assert.equal(lstatSync(path.join(root, 'GOAL.md')).isSymbolicLink(), true);
    const result = persist(root, contract(), [
      '--replace',
      '--expected-sha256',
      hash('outside stays unchanged\n'),
    ]);
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /symlink|reparse/i);
    assert.equal(readFileSync(destination, 'utf8'), 'outside stays unchanged\n');
  } finally {
    rmSync(root, { recursive: true, force: true });
    rmSync(outside, { recursive: true, force: true });
  }
});

test('lint, invalid UTF-8, and secret failures leave no target or temp file', () => {
  const root = makeRepo();
  try {
    const samples = [
      contract().replace('## Completion conditions', '## Missing completion'),
      contract().replace(
        'The current failure is local',
        'Authorization: Bearer abcdefghijklmnopqrstuvwxyz012345',
      ),
    ];
    for (const body of samples) {
      const result = persist(root, body);
      assert.notEqual(result.status, 0);
      assert.doesNotMatch(result.stderr, /abcdefghijklmnopqrstuvwxyz012345/);
    }
    const invalid = persist(root, Buffer.from([0xc3, 0x28]));
    assert.notEqual(invalid.status, 0);
    assert.match(invalid.stderr, /UTF-8/);
    assert.equal(existsSync(path.join(root, 'GOAL.md')), false);
    assert.deepEqual(readdirSync(root).filter((name) => name.endsWith('.tmp')), []);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

