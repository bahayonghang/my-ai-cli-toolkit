test('one neutral contract can carry all five thin launch renderers', () => {
  const root = makeRepo();
  try {
    const result = persist(root, allPlatformContract(), ['--name', 'GOAL-all.md']);
    assert.equal(result.status, 0, result.stderr);
    const body = readFileSync(path.join(root, 'GOAL-all.md'), 'utf8');
    assert.equal((body.match(/^# Goal Contract:/gm) ?? []).length, 1);
    for (const label of ['Codex', 'Claude Code', 'Grok Build', 'Oh My Pi', 'Kimi Code']) {
      assert.match(body, new RegExp(`^- ${label}:`, 'm'));
    }
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

