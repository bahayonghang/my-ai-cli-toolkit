function contract({ platform = 'codex', title = 'Parser recovery', target = 'GOAL.md' } = {}) {
  const platformName = {
    codex: 'Codex',
    claude: 'Claude Code',
    grok: 'Grok Build',
    omp: 'Oh My Pi',
    kimi: 'Kimi Code',
  }[platform];
  const launcher = launchers[platform]
    .replaceAll('./GOAL.md', `./${target}`)
    .replaceAll('@GOAL.md', `@${target}`);
  return `# Goal Contract: ${title}

## Contract metadata
- Status: approved
- Target platform: ${platform}
- Generated by: goal-meta-skill 0.6.0
- Project root: .
- Contract path: ${target}
- Baseline: main @ 0123456789abcdef0123456789abcdef01234567; dirty paths: clean
- Generated at: 2026-08-23T12:00:00+08:00

## Authority and startup
Follow system and user instructions, scoped AGENTS.md or CLAUDE.md rules, and authoritative project or Trellis task specifications before this contract. Recheck the baseline and stop to report any drift or conflict before risky edits.

## Objective
Repair the parser so blank CSV rows no longer crash the local command while preserving current output for nonblank rows.

## Required reading and current context
- Read AGENTS.md, src/parser/, tests/parser/, and the project command source before editing.
- The current failure is local and contains no credential or private-data context.

## Scope and boundaries
- Write only under src/parser/ and tests/parser/; preserve unrelated dirty files and generated output.

## Constraints
- Add no dependency, remote action, production mutation, destructive operation, credential, or paid service.

## Verification
- VERIFIED baseline command: run just test-parser and retain its exit code and output.
- UNVERIFIED runtime evidence: exercise one blank-row input after implementation and report the result.

## Iteration policy
Make one focused change, rerun the smallest failing check, inspect new evidence before retrying, and stop after three evidence-driven repair rounds.

## Completion conditions
1. The blank-row regression test passes.
2. just test-parser exits zero and the current diff remains inside the approved boundary.

## Pause / stop conditions
Pause or stop and report when authority conflicts, baseline drift, credentials, production data, destructive actions, or a fourth failed repair round is reached; budget exhaustion is not completion.

## Launch commands
- ${platformName}: \`${launcher}\`
`;
}

function persist(root, body, extraArgs = []) {
  return runPython([helper, '--repo-root', root, ...extraArgs], body);
}

function allPlatformContract(target = 'GOAL-all.md') {
  const lines = Object.entries(launchers).map(([platform, launcher]) => {
    const label = {
      codex: 'Codex',
      claude: 'Claude Code',
      grok: 'Grok Build',
      omp: 'Oh My Pi',
      kimi: 'Kimi Code',
    }[platform];
    const rendered = launcher
      .replaceAll('./GOAL.md', `./${target}`)
      .replaceAll('@GOAL.md', `@${target}`);
    return `- ${label}: \`${rendered}\``;
  });
  return contract({ target })
    .replace('- Target platform: codex', '- Target platform: codex, claude, grok, omp, kimi')
    .replace(/- Codex: `\/goal[^\n]+`/, lines.join('\n'));
}

test('create-only writes UTF-8 LF, reports untracked metadata, and does not echo body', () => {
  const root = makeRepo();
  try {
    const body = contract({ title: '解析器恢复' }).replaceAll('\n', '\r\n');
    const result = persist(root, body);
    assert.equal(result.status, 0, result.stderr);
    const report = JSON.parse(result.stdout);
    assert.deepEqual(Object.keys(report).sort(), ['action', 'bytes', 'git_visibility', 'path', 'sha256']);
    assert.equal(report.action, 'created');
    assert.equal(report.path, 'GOAL.md');
    assert.equal(report.git_visibility, 'untracked');
    assert.doesNotMatch(result.stdout, /Parser recovery|解析器恢复|Repair the parser/);
    const bytes = readFileSync(path.join(root, 'GOAL.md'));
    assert.equal(bytes.includes(Buffer.from('\r\n')), false);
    assert.equal(bytes.toString('utf8').startsWith('# Goal Contract: 解析器恢复'), true);
    assert.equal(report.bytes, bytes.length);
    assert.equal(report.sha256, createHash('sha256').update(bytes).digest('hex'));
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('existing target is preserved until replace has the matching SHA-256', () => {
  const root = makeRepo();
  try {
    const oldBody = contract();
    assert.equal(persist(root, oldBody).status, 0);

    const conflict = persist(root, contract({ title: 'Changed' }));
    assert.notEqual(conflict.status, 0);
    assert.match(conflict.stderr, /already exists/);
    assert.equal(readFileSync(path.join(root, 'GOAL.md'), 'utf8'), oldBody);

    const stale = persist(root, contract({ title: 'Changed' }), [
      '--replace',
      '--expected-sha256',
      '0'.repeat(64),
    ]);
    assert.notEqual(stale.status, 0);
    assert.match(stale.stderr, /SHA-256 mismatch/);
    assert.equal(readFileSync(path.join(root, 'GOAL.md'), 'utf8'), oldBody);

    const replacement = contract({ title: 'Changed' });
    const replaced = persist(root, replacement, [
      '--replace',
      '--expected-sha256',
      hash(oldBody),
    ]);
    assert.equal(replaced.status, 0, replaced.stderr);
    assert.equal(JSON.parse(replaced.stdout).action, 'replaced');
    assert.equal(readFileSync(path.join(root, 'GOAL.md'), 'utf8'), replacement);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

