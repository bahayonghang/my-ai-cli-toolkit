test('Git visibility distinguishes ignored and tracked contracts', () => {
  const ignoredRoot = makeRepo();
  const trackedRoot = makeRepo();
  try {
    writeFileSync(path.join(ignoredRoot, '.gitignore'), 'GOAL.md\n', 'utf8');
    const ignored = persist(ignoredRoot, contract());
    assert.equal(ignored.status, 0, ignored.stderr);
    assert.equal(JSON.parse(ignored.stdout).git_visibility, 'ignored');

    assert.equal(persist(trackedRoot, contract()).status, 0);
    git(trackedRoot, ['add', 'GOAL.md']);
    const current = readFileSync(path.join(trackedRoot, 'GOAL.md'), 'utf8');
    const replaced = persist(trackedRoot, contract({ title: 'Tracked change' }), [
      '--replace',
      '--expected-sha256',
      hash(current),
    ]);
    assert.equal(replaced.status, 0, replaced.stderr);
    assert.equal(JSON.parse(replaced.stdout).git_visibility, 'tracked');
  } finally {
    rmSync(ignoredRoot, { recursive: true, force: true });
    rmSync(trackedRoot, { recursive: true, force: true });
  }
});

